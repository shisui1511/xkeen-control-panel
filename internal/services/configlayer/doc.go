// Package configlayer — фундамент слоя «Конфигурация».
//
// Слой работает за флагом config_layer (D-01) и хранит единое состояние
// конфигурации панели: черновик, применённое состояние, манифест файлов,
// принадлежащих панели, уведомления и журнал записи. Состояние лежит одним
// JSON-файлом в каталоге данных панели (StateFileName), правки черновика
// защищены номером ревизии (сравнить и записать), изменения рассылаются
// подписчикам через шину событий (Broker) для SSE.
//
// Пакет ничего не знает про HTTP: обработчики и маршруты живут в
// internal/handlers и используют Store и Broker как обычные зависимости.
