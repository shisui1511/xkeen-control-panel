// Package routing — общая модель маршрутизации для двух ядер: группы узлов,
// правила, параметры проверки узлов и представление для вкладок «Группы» и
// «Правила» (U-01…U-06).
//
// Модель живёт в секциях черновика слоя «Конфигурация» (groups, rules, probe) и
// не зависит от ядра: Xray и Mihomo получают из неё свои файлы от генераторов,
// которые чисты и детерминированны. Правки секций идут только через Service
// (SaveGroup, SaveRule и остальные): каждая — одна ревизия черновика с проверкой
// ввода, поэтому клиент не пишет секции в обход сервиса.
//
// Состав группы считает одна функция Resolve по каталогу узлов источников;
// второго расчёта нет ни в предпросмотре, ни в представлении, ни в генераторах.
// Так же единственный расчёт проблем — analyze: проверка до записи
// (Service.Checker) берёт из него блокирующие проблемы, а Service.View — те же
// проблемы и предупреждения для интерфейса.
