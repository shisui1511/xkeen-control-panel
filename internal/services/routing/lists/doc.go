//   - выгрузку категории в строки текстового провайдера Mihomo (Index.Extract)
//     с пределами размера;
//   - каталог сервисов и стран (Resolve) по данным catalog.json и точечную
//     запись geodata в xkeen.json (GeodataStore) только из встроенного каталога.
