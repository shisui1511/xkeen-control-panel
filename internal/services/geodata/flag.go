package geodata

// Приостановка расписания панели (State.Suspended, D-36) осталась от выключения
// флага слоя прежних версий: тогда расписание возвращалось cron XKeen. Флага больше
// нет, и приостановка сама не снимается — расписание панели не стартует от одного
// обновления. Её снимают только явные действия владельца: «Перенять расписание»
// (CronAction adopt), «Отдать XKeen» (give) или сохранение включённого расписания,
// когда перенимать нечего (SetSchedule). Сохранённая строка cron при этом не
// переписывается.

// scheduleActive — расписание панели должно срабатывать: включено и не
// приостановлено.
func (s *Service) scheduleActive(sch Schedule, suspended bool) bool {
	return sch.Enabled && !suspended
}
