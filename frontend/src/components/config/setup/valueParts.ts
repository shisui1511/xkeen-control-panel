// Строки мастера вида «Подпись: значение» со значением конфигурации (имя ядра, число,
// адрес). Перевод запрашивается с меткой VALUE_MARK на месте значения и делится по ней на
// текст до и после; само значение рисуется отдельным элементом — моноширинным (.setup-mono,
// .ip-value). Так порядок слов остаётся за словарём, а значение не попадает в HTML.

/** Метка места значения в переведённой строке. */
export const VALUE_MARK = '\u0000';

/** Делит переведённую строку по первой метке: [до, после]; метки нет — [вся строка, '']. */
export function valueParts(text: string): [string, string] {
  const i = text.indexOf(VALUE_MARK);
  return i < 0 ? [text, ''] : [text.slice(0, i), text.slice(i + VALUE_MARK.length)];
}
